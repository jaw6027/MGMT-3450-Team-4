const researchFields = ["website", "contactUrl", "productCategory", "fitCategory", "whyPotential", "reviewedOn", "sourceUrls"];
export function addCaliforniaProspects(state) {
  const names = new Set(state.contacts.map(c => c.business.trim().toLowerCase()));
  const ids = new Set(state.contacts.map(c => c.id));
  let changed = false;
  const contacts = state.contacts.map(c => {
    const match = californiaProspects.find(p => p.id === c.id || p.business.trim().toLowerCase() === c.business.trim().toLowerCase());
    if (!match) return c;
    const missing = researchFields.filter(key => c[key] === undefined);
    if (!missing.length) return c;
    changed = true;
    return { ...c, ...Object.fromEntries(missing.map(key => [key, structuredClone(match[key])])) };
  });
  const additions = californiaProspects.filter(c => !ids.has(c.id) && !names.has(c.business.trim().toLowerCase()));
  if (!changed && !additions.length) return state;
  return { ...state, contacts: [...contacts, ...structuredClone(additions)] };
}
